"""The read-only role ``ar3_reader`` for analysis notebooks (§12a.4).

Its password is COCKPIT_DB_READER_PASSWORD from .env (generated by cockpit.sh); without one
the role exists but cannot log in. Roles are cluster-wide, so the test database's migration
reuses the role and only adds the grants.
"""

import os

from django.db import migrations

READ = (
    "telemetry_session",
    "telemetry_run",
    "telemetry_recording",
    "joint_samples",
    "gripper_samples",
    "safety_samples",
    "metrics",
    "events",
    "detections",
    "trajectories",
    "joint_stats_1s",
    "joint_stats_1m",
)


def create(apps, schema_editor):
    password = os.environ.get("COCKPIT_DB_READER_PASSWORD", "")
    db = schema_editor.connection.settings_dict["NAME"]
    with schema_editor.connection.cursor() as cur:
        cur.execute("SELECT 1 FROM pg_roles WHERE rolname = 'ar3_reader'")
        if cur.fetchone() is None:
            cur.execute("CREATE ROLE ar3_reader NOLOGIN")
        if password:
            cur.execute("ALTER ROLE ar3_reader LOGIN PASSWORD %s", [password])
        cur.execute(f'GRANT CONNECT ON DATABASE "{db}" TO ar3_reader')
        cur.execute("GRANT USAGE ON SCHEMA public TO ar3_reader")
        cur.execute(f"GRANT SELECT ON {', '.join(READ)} TO ar3_reader")


def revoke(apps, schema_editor):
    with schema_editor.connection.cursor() as cur:
        cur.execute(f"REVOKE SELECT ON {', '.join(READ)} FROM ar3_reader")


class Migration(migrations.Migration):
    dependencies = [("telemetry", "0003_aggregates")]

    operations = [migrations.RunPython(create, revoke)]
